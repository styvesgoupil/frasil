"""FRASIL's logo for the screen: the PNG (light on dark) cropped to the drawing, scaled to WIDTH pixels with
antialiasing, and written as 4-bit intensities (0 the background, 15 the brightest letters), two to a byte.
The lower half of the letters is paler in the drawing, and stays so here: the intensity carries it.

  gen_logo.py LOGO.png OUT.h [WIDTH]
"""
import sys
from PIL import Image, ImageFilter

src, out = sys.argv[1], sys.argv[2]
width = int(sys.argv[3]) if len(sys.argv) > 3 else 216

im = Image.open(src).convert("RGB")
lum = im.convert("L")
bg = sorted(lum.getpixel((x, y)) for x in (4, im.width - 5) for y in (4, im.height - 5))[1]
mask = lum.point(lambda v: 255 if v > bg + 18 else 0)
box = mask.getbbox()
if not box:
    raise SystemExit("gen_logo: nothing drawn in " + src)
crop = lum.crop(box).filter(ImageFilter.MedianFilter(7))   # the drawing's grain out: flat letters
h = max(1, round(crop.height * width / crop.width))
small = crop.resize((width, h), Image.LANCZOS)
hist = sorted(crop.get_flattened_data() if hasattr(crop, "get_flattened_data") else crop.getdata())
top = hist[int(len(hist) * 0.995)]                  # the brightest letters
vals = small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata()
px = [max(0, min(15, round((v - bg) * 15 / max(1, top - bg)))) for v in vals]
rows = [sum(px[y * width:(y + 1) * width]) for y in range(h)]
mid = [y for y in range(h // 4, 3 * h // 4)]
cut = min(mid, key=lambda y: rows[y]) if mid else h // 2   # the waterline: the emptiest row across the middle
# the letters flat in two tones, as drawn: full above the waterline, paler under it (the edges keep their
# antialiasing)
for y in range(h):
    full, floor = (15, 12) if y < cut else (12, 10)
    for x in range(width):
        if px[y * width + x] >= floor:
            px[y * width + x] = full
data = bytearray()
for y in range(h):
    for x in range(0, width, 2):
        a = px[y * width + x]
        b = px[y * width + x + 1] if x + 1 < width else 0
        data.append(a << 4 | b)
with open(out, "w") as f:
    f.write("/* generated by tools/gen_logo.py from %s: do not edit */\n" % src.split("/")[-1])
    f.write("#define LOGO_W %du\n#define LOGO_H %du\n#define LOGO_CUT %du   /* the waterline's row */\n" % (width, h, cut))
    f.write("static const uint8_t LOGO_PX[%d] = {\n" % len(data))
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print(f"logo: {width} x {h}, waterline at {cut}, {len(data)} B")
